function renderGallery() {
  const root = document.querySelector("[data-gallery-grid]");
  const previewRoot = document.querySelector("[data-gallery-preview]");

  const filterButtons = document.querySelectorAll("[data-gallery-filter]");
  let active = "all";

  function paint() {
    if (!root) return;
    const items = GALLERY.filter((item) => active === "all" || item.category === active);
    root.innerHTML = items.map(renderGalleryCard).join("");
  }

  filterButtons.forEach((button) => {
    button.addEventListener("click", () => {
      active = button.dataset.galleryFilter || "all";
      filterButtons.forEach((btn) => {
        btn.setAttribute("aria-pressed", String(btn === button));
      });
      paint();
    });
  });

  paint();

  if (previewRoot) {
    previewRoot.innerHTML = GALLERY.slice(0, 3).map(renderGalleryCard).join("");
  }
}

